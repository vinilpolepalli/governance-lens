import { chromium } from 'playwright';
const b = await chromium.launch();
const d = await b.newPage({ viewport: { width: 1280, height: 900 } });
await d.goto('https://service-flow-vinilpolepallis-projects.vercel.app', { waitUntil: 'networkidle' });
await d.screenshot({ path: '/tmp/bel-d.png' });
await d.locator('article, [class*=ticket]').first().click().catch(()=>{});
await d.waitForTimeout(400);
await d.screenshot({ path: '/tmp/bel-d-detail.png' });
const m = await b.newPage({ viewport: { width: 390, height: 844 } });
await m.goto('https://service-flow-vinilpolepallis-projects.vercel.app', { waitUntil: 'networkidle' });
await m.screenshot({ path: '/tmp/bel-m.png' });
await b.close(); console.log('done');

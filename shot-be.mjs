import { chromium } from 'playwright';
const b = await chromium.launch();
const d = await b.newPage({ viewport: { width: 1280, height: 900 } });
await d.goto('http://127.0.0.1:8931/', { waitUntil: 'networkidle' });
await d.screenshot({ path: '/tmp/be-d.png' });
await d.getByText('PART DELAYED', { exact: true }).first().click().catch(()=>console.log('chip-skip'));
await d.waitForTimeout(300);
await d.screenshot({ path: '/tmp/be-d-filter.png' });
await d.getByText('ALL', { exact: true }).click().catch(()=>{});
await d.waitForTimeout(300);
const card = d.locator('[class*=ticket], article, li').first();
await card.click().catch(()=>console.log('card-skip'));
await d.waitForTimeout(400);
await d.screenshot({ path: '/tmp/be-d-detail.png' });
const m = await b.newPage({ viewport: { width: 390, height: 844 } });
await m.goto('http://127.0.0.1:8931/', { waitUntil: 'networkidle' });
await m.screenshot({ path: '/tmp/be-m.png' });
await m.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
await m.waitForTimeout(300);
await m.screenshot({ path: '/tmp/be-m2.png' });
await b.close(); console.log('done');

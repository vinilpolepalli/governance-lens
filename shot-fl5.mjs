import { chromium } from 'playwright';
const b = await chromium.launch();
const d = await b.newPage({ viewport: { width: 1280, height: 900 } });
await d.goto('http://127.0.0.1:8923/', { waitUntil: 'networkidle' });
await d.locator('td a').first().click({ timeout: 8000 });
await d.waitForTimeout(400);
await d.screenshot({ path: '/tmp/fl5-d-selected.png' });
await d.locator('select, [role=combobox]').count();
await d.locator('text=Practice admin').click().catch(()=>{});
await d.waitForTimeout(400);
await d.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
await d.waitForTimeout(300);
await d.screenshot({ path: '/tmp/fl5-d-audit.png' });
await b.close(); console.log('done');

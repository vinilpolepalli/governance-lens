import { chromium } from 'playwright';
const b = await chromium.launch();
const d = await b.newPage({ viewport: { width: 1280, height: 900 } });
await d.goto('https://access-studio.vercel.app', { waitUntil: 'networkidle' });
await d.screenshot({ path: '/tmp/fll-d.png' });
await d.locator('td button').first().click();
await d.waitForTimeout(400);
await d.screenshot({ path: '/tmp/fll-d-selected.png' });
await d.getByText('Practice admin', { exact: true }).click();
await d.waitForTimeout(400);
await d.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
await d.waitForTimeout(300);
await d.screenshot({ path: '/tmp/fll-d-audit.png' });
const m = await b.newPage({ viewport: { width: 390, height: 844 } });
await m.goto('https://access-studio.vercel.app', { waitUntil: 'networkidle' });
await m.locator('button.link, td button').first().click().catch(()=>{});
await m.waitForTimeout(400);
await m.screenshot({ path: '/tmp/fll-m.png' });
await b.close(); console.log('done');
